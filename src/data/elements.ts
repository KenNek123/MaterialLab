export function getElementInfo(symbol: string): ElementDetail | null {
  if (!symbol) return null;
  const clean = symbol.replace(/[⁺⁻\d]/g, '').trim();
  const found = ELEMENT_REGISTRY[symbol] || ELEMENT_REGISTRY[clean];
  return found ?? null;
}
